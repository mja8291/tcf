// Postbuild step (see package.json's "build" script) — writes
// public/precache-manifest.js, which public/sw.js imports at install time.
//
// Why this exists: the service worker used to only cache a page's HTML
// *after* someone visited it online at least once (networkFirst's cache
// fallback in sw.js). That's fine for pages revisited later, but breaks the
// very scenario offline support exists for — a surveyor whose connection
// drops (or whose Android TWA gets killed and cold-restarts) on a scoring
// page they hadn't happened to load before. That request is a fresh
// "navigate", nothing's cached for it yet, and they hit the generic
// /offline.html dead end mid-assessment instead of their actual survey —
// confirmed happening on the Play Store Android app, 2026-09-17.
//
// The fix is to precache every route's HTML *and* every JS/CSS chunk it
// needs at install time, straight from the just-built output, so the whole
// app is available offline from the very first launch — not just pages
// that happened to get visited online first. Every route here is a fully
// static, prerendered page (`next build`'s own "○ (Static)" marker), so its
// built HTML already contains the exact <script>/<link> tags a real visit
// would load; this just extracts those asset URLs so they can be cached
// too, without needing a full Workbox-style build pipeline for something
// this small and fixed a route list.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const APP_DIR = join(ROOT, ".next", "server", "app");

// Every route worth being able to open with zero connectivity. Deliberately
// hand-maintained, not auto-discovered — API routes and error boundaries
// (_not-found, _global-error) don't belong here, and a route added later
// needs a human to notice it should be offline-capable too.
const ROUTES = [
  "/",
  "/dashboard",
  "/privacy",
  "/terms",
  "/survey/find-school",
  "/survey/method",
  "/survey/m1",
  "/survey/m1/campus-visit",
  "/survey/m2",
  "/survey/m2/location",
  "/survey/m2/location/name",
  "/survey/m2/location/classroom",
  "/survey/m2/category",
  "/survey/review",
  "/survey/resume",
  "/survey/done",
];

function htmlFileFor(route) {
  return join(APP_DIR, route === "/" ? "index.html" : `${route.slice(1)}.html`);
}

// Build output escapes "/" as "\/" inside the embedded RSC payload script,
// so a raw regex match on `/_next/static/...` can trail a stray backslash
// or quote — strip those rather than trying to out-clever the escaping.
function extractAssetUrls(html) {
  const matches = html.match(/\/_next\/static\/[^\s"'\\]+/g) ?? [];
  return matches.map((m) => m.replace(/[\\"']+$/, ""));
}

const pages = [];
const assets = new Set();

for (const route of ROUTES) {
  const file = htmlFileFor(route);
  let html;
  try {
    html = readFileSync(file, "utf8");
  } catch {
    throw new Error(
      `generate-sw-precache: expected built HTML for route "${route}" at ${file} but it's missing — ` +
        `did the route get renamed/removed? Update ROUTES in scripts/generate-sw-precache.mjs to match.`
    );
  }
  pages.push(route);
  for (const url of extractAssetUrls(html)) assets.add(url);
}

const assetList = [...assets].sort();
// Cache names only change (busting every previous entry — see sw.js's
// activate handler) when the actual precached content changes, not on
// every build — a build with identical output shouldn't force every
// installed client to redownload everything for no reason.
const version = createHash("sha1").update(JSON.stringify([pages, assetList])).digest("hex").slice(0, 12);

const out = `// Generated by scripts/generate-sw-precache.mjs — do not edit by hand.
self.__PRECACHE_VERSION = ${JSON.stringify(version)};
self.__PRECACHE_PAGES = ${JSON.stringify(pages, null, 2)};
self.__PRECACHE_ASSETS = ${JSON.stringify(assetList, null, 2)};
`;

writeFileSync(join(ROOT, "public", "precache-manifest.js"), out);
console.log(
  `generate-sw-precache: wrote ${pages.length} pages + ${assetList.length} assets (version ${version}) to public/precache-manifest.js`
);
